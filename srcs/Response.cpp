bool Response::finalize_response(std::string co_status) {
	add_to_headers<size_t>("Content-Length", _response_body.str().size());
	add_to_headers<std::string>("Connection", co_status);
	_response = _status_line.str() + _headers.str() + "\r\n" + _response_body.str();
	_status_line.str(""); _headers.str(""); _response_body.str("");
	return true;
}

std::string	Response::get_content_type(const std::string & file_path) const {
	std::string::size_type dot = file_path.find_last_of('.');
	if (dot == std::string::npos)
		return "application/octet-stream";

	std::string ext = to_lower_copy(file_path.substr(dot));
	if (ext == ".html" || ext == ".htm") return "text/html; charset=utf-8";
	if (ext == ".css") return "text/css; charset=utf-8";
	if (ext == ".js") return "application/javascript; charset=utf-8";
	if (ext == ".json") return "application/json; charset=utf-8";
	if (ext == ".txt") return "text/plain; charset=utf-8";
	if (ext == ".xml") return "application/xml; charset=utf-8";
	if (ext == ".svg") return "image/svg+xml";
	if (ext == ".png") return "image/png";
	if (ext == ".jpg" || ext == ".jpeg") return "image/jpeg";
	if (ext == ".gif") return "image/gif";
	if (ext == ".ico") return "image/x-icon";
	if (ext == ".webp") return "image/webp";
	if (ext == ".pdf") return "application/pdf";
	if (ext == ".wasm") return "application/wasm";
	return "application/octet-stream";
}

client_status Response::send_response(void) {
	// log_warning<std::string>("Sending response to client fd ", _response);
	if (_response.empty()) {
		log_error("Response is empty, nothing to send");
		return WAITING;
	}
	ssize_t	bytes_send = send(_fd, _response.c_str(), _response.size(), MSG_NOSIGNAL);
	if (bytes_send == -1) {
		log_error(strerror(errno));
		log_error("Failed to send response to client");
		return WAITING;
	}
	// log_debug<size_t>("Response size", _response.size());
	// log_debug<ssize_t>("Bytes send", bytes_send);
	if (static_cast<size_t>(bytes_send) == _response.size())
		return WAITING;
	size_t	by = static_cast<size_t>(bytes_send);
	// log_debug<size_t>("Size_t bytes", by);
	_response.erase(0, by);
	return SENDING_RESPONSE;
}
