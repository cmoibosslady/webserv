client_status	Response::prepare_redirect(const std::string & uri) {
	log_info("Preparing response for redirect");
	classic_http_hat(_rewrite->error_code);

	const std::string & replacm = _rewrite->replacement;
	add_to_headers<std::string>("Location", replacm.substr(0, replacm.find("/$1")) + uri.substr(uri.find(_location->path) + _location->path.size()));
	return SENDING_RESPONSE;
}

client_status 	Response::prepare_post(const std::string &uri, const std::string &body, const std::string &body_type) {
	log_info("Preparing response for POST");
	if (body.size() > _server->client_max_body_size) {
		log_debug<size_t>("Body size is", body.size());
		log_debug<size_t>("Client max body size is", _server->client_max_body_size);
		prepare_error_response(413);
		return SENDING_RESPONSE;
	}
	std::string file_path = uri.substr(uri.find(_location->path) + _location->path.size(), uri.find("?"));
	log_debug<std::string>("File path for POST request", file_path);
	log_debug<std::string>("with body type", body_type);
	if (body_type.substr(0, body_type.find(";")) == "multipart/form-data") {
		if (_location->upload_auth == false) {
			prepare_error_response(403);
			return SENDING_RESPONSE;
		}
		file_path = _location->upload_path + file_path;
		log_warning<std::string>("Trying to create new file", file_path);
		std::ofstream	new_file(file_path.c_str());
		if (new_file.fail()) {
			prepare_error_response(500);
			return SENDING_RESPONSE;
		}
		new_file << body;
		new_file.close();
		classic_http_hat(201);
		return SENDING_RESPONSE;
	}
	else {
		log_info("So not an upload");
		if (access(file_path.c_str(), F_OK | W_OK) == -1) {
		// modify file
			prepare_error_response(403);
			return SENDING_RESPONSE;
		}
	}
	classic_http_hat(200);
	return SENDING_RESPONSE;
}

client_status	Response::prepare_delete(const std::string &uri) {
	std::string file_path = uri.substr(0, uri.find("?"));
	file_path = _location->root + file_path.substr(file_path.find(_location->path) + _location->path.size());
	if (access(file_path.c_str(), F_OK) == -1) {
		prepare_error_response(404);
		return SENDING_RESPONSE;
	}
	if (remove(file_path.c_str()) == -1) {
		prepare_error_response(500);
		return SENDING_RESPONSE;
	}
	classic_http_hat(200);
	return SENDING_RESPONSE;
}

client_status	Response::prepare_get(const std::string &uri) {
	std::string file_path = uri.substr(0, uri.find("?"));
	file_path = file_path.substr(file_path.find(_location->path) + _location->path.size());
	if (file_path[0] == '/')
		file_path.erase(0, 1);
	file_path = _location->root + file_path;
	log_debug<std::string>("Prepared file path for GET: ", file_path);
	if (file_path.at(file_path.size() - 1) == '/') {
		if (_location->autoindex == true) {
			prepare_auto_index(uri.substr(0, uri.find("?")), file_path);
			return SENDING_RESPONSE;
		}
		if (_location->index_files.empty()) {
			prepare_error_response(403);
			return SENDING_RESPONSE;
		}
		for (std::set<std::string>::const_iterator it = _location->index_files.begin(); it != _location->index_files.end(); ++it) {
			std::string index_file = file_path + *it;
			if (access(index_file.c_str(), F_OK) != -1) {
				file_path = index_file;
				break ;
			}
		}
	}
	if (access(file_path.c_str(), F_OK) == -1) {
		prepare_error_response(404);
		return SENDING_RESPONSE;
	}
	if (access(file_path.c_str(), R_OK) == -1) {
		prepare_error_response(403);
		return SENDING_RESPONSE;
	}
	std::ifstream	ifs(file_path.c_str());
	if (ifs.is_open()) {
		classic_http_hat(200);
		add_to_headers<std::string>("Content-type", get_content_type(file_path));
		_response_body << ifs.rdbuf();
		ifs.close();
		return SENDING_RESPONSE;
	}
	else {
		prepare_error_response(500);
		return SENDING_RESPONSE;
	}
}

bool	Response::is_raw_cgi(const std::string &cgi_answer) {
	if (cgi_answer.find("Status: ") < cgi_answer.find("\r\n"))
		return false;
	return true;
}

void	Response::prepare_cgi(const std::string &cgi_answer) {
	// log_info("Preparing response after CGI");
	// log_debug<std::string>("CGI output", cgi_answer);
	
	if (is_raw_cgi(cgi_answer) == true) {
		_status_line << "HTTP/1.1 200 CGI OK\r\n";
		add_to_headers<std::string>("Content-type", "application/octet-stream");
		_response_body << cgi_answer;
		return ;
	}

	std::stringstream output(cgi_answer);
	std::string line;
	// SUPPOSING CGI ARE HTTP ENCODED
	while (std::getline(output, line)) {
		if (line == "\r")
			break ; // end of headers
		if (line.find("Status: ") != std::string::npos) {
			classic_http_hat(std::atoi(line.substr(line.find("Status: ") + 8).c_str()));
		}
		else {
			_headers << line << "\r\n";
		}
	}
	_response_body << output.rdbuf();
}


