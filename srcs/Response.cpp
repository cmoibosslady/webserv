void	Response::classic_http_hat(int http_code) {
	const std::string empty_body;
	log_debug<int>("Building response with HTTP code ", http_code);
	_status_line << "HTTP/1.1 " << http_code << " " << get_reason_phrase(http_code) << "\r\n";
}

void	Response::prepare_error_content(int http_code) {
	if (_error_pages.find(http_code) != _error_pages.end()) {
		if (access(_error_pages.at(http_code).c_str(), F_OK | R_OK) != -1) {
			std::ifstream	ifs(_error_pages.at(http_code).c_str());
			if (ifs.is_open()) {
				_response_body << ifs.rdbuf();;
				ifs.close();
				return ;
			}
			log_error("Error page is not open");
		}
		log_error("Cannot access error page: " + _error_pages.at(http_code));
	}
	log_info("No pages found for this error");
	log_debug<size_t>("Size of error pages", _error_pages.size());
	_response_body << build_default_error_page(http_code);
	return ;
}

void	Response::prepare_error_response(int http_code) {
	classic_http_hat(http_code);
	prepare_error_content(http_code);
}

void	Response::prepare_auto_index(const std::string &uri, const std::string &dir_path) {
	DIR *dir = opendir(dir_path.c_str());
	if (dir == NULL) { prepare_error_response(500); return ; }
	classic_http_hat(200);
	_response_body << "<!DOCTYPE html><html><head><title>Index of " 
		<< uri << "</title></head><body>"
		<< "<h1>Index of " << uri << "</h1>"
		<< "<hr><pre>" ;

	struct dirent *entry;
	while ((entry = readdir(dir)) != NULL) {
		std::string name = entry->d_name;
		if (name == ".") { continue ; }
		std::string display_name = name;
		if (entry->d_type == DT_DIR) { display_name += "/"; }
		std::string href;
		if (name == "..") { href = name; }
		else {
			std::string base_uri = uri;
			if (!base_uri.empty() && base_uri[base_uri.size() - 1] != '/') { base_uri += "/"; }
			href = base_uri + name;
			if (entry->d_type == DT_DIR) { href += "/"; }
		}
		_response_body << "<a href=\"" << href << "\">" << display_name << "</a>" << std::endl; 
	}
	closedir(dir);
	_response_body << "</pre><hr></body></html>";
}

